const commonDocs = ['Aadhaar card', 'Bank account details', 'Recent passport photo']

function normalizeEligibility(e: Scheme['eligibility'] | undefined): Scheme['eligibility'] {
  return {
    minAge: e?.minAge ?? null,
    maxAge: e?.maxAge ?? null,
    maxIncome: e?.maxIncome ?? null,
    gender: e?.gender ?? null,
    casteCategory: e?.casteCategory ?? null,
    states: e?.states ?? null,
    userType: e?.userType ?? null,
  }
}

function normalizeScheme(s: Scheme): Scheme {
  return {
    ...s,
    updatedAt: s.updatedAt ?? '2026-04-01',
    eligibility: normalizeEligibility(s.eligibility),
    documents: Array.isArray(s.documents) && s.documents.length ? s.documents : [...commonDocs],
    applicationSteps:
      Array.isArray(s.applicationSteps) && s.applicationSteps.length
        ? s.applicationSteps
        : ['Open the official link.', 'Check eligibility and required documents.', 'Apply online or via nearest help center (CSC/office).'],
    deadline: s.deadline ?? null,
  }
}

