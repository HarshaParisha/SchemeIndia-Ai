function applyTemplate(t: string, stateName: string) {
  return t.replace(/\{state\}/g, stateName)
}

function ensureRegionalSchemeCount(stateName: string, target: number) {
  const current = SCHEMES.filter((s) => s.state === stateName).length
  if (current >= target) return

  const isUt = UT_SET.has(stateName)
  const authority = isUt
    ? `${stateName} Administration`
    : `Government of ${stateName}`
  const baseLink = 'https://www.india.gov.in/my-government/schemes'

  let remaining = target - current
  const used = new Set(SCHEMES.map((s) => s.id))
  for (const tpl of GENERIC_TEMPLATES) {
    if (remaining <= 0) break
    const id = `${slugId(stateName)}-${tpl.key}`
    if (used.has(id)) continue
    SCHEMES.push(
      normalizeScheme({
        id,
        name: applyTemplate(tpl.name, stateName),
        ministry: authority,
        state: stateName,
        category: tpl.category,
        description: applyTemplate(tpl.description, stateName),
        benefit: applyTemplate(tpl.benefit, stateName),
        eligibility: { states: [stateName] },
        documents: [...commonDocs, 'Residence proof (as applicable)'],
        applicationSteps: ['Open the official link.', 'Check eligibility and required documents.', 'Apply online or via nearest help center (CSC/office).'],
        officialLink: baseLink,
        deadline: null,
      }),
    )
    used.add(id)
    remaining -= 1
  }
}

for (const region of IN_STATES) {
  ensureRegionalSchemeCount(region, UT_SET.has(region) ? 25 : 50)
}

for (let i = 0; i < SCHEMES.length; i++) {
  SCHEMES[i] = normalizeScheme(SCHEMES[i])
}
